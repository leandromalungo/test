/**
 * Gera observações diárias determinísticas de demonstração explicitamente marcadas como
 * `isSimulatedData: true` para ilustrar cenários de seca, chuva normal, excesso e dados insuficientes.
 */
function buildDemoDailySeries(
  providerCode: 'open_meteo_era5' | 'nasa_power',
  providerName: string,
  latitude: number,
  longitude: number,
  startDate: string,
  days: number,
  dailyPattern: (index: number) => number | null
): ClimateObservation[] {
  const results: ClimateObservation[] = []
  const base = new Date(`${startDate}T00:00:00Z`)
  for (let i = 0; i < days; i++) {
    const d = new Date(base)
    d.setUTCDate(base.getUTCDate() + i)
    const isoDate = d.toISOString().slice(0, 10)
    const precip = dailyPattern(i)
    results.push({
      id: `obs-seed-${providerCode}-${latitude.toFixed(2)}-${isoDate}`,
      providerCode,
      providerName,
      latitude,
      longitude,
      observationDate: isoDate,
      precipitationMm: precip,
      unit: 'mm',
      retrievedAt: '2026-11-10T08:00:00.000Z',
      sourceUrl: `demo://seed/${providerCode}/${isoDate}`,
      spatialResolution: providerCode === 'open_meteo_era5' ? '~9 km (Simulado)' : '~50 km (Simulado)',
      qualityStatus: precip === null ? 'insufficient' : 'valid',
      isSimulatedData: true,
      rawPayloadReference: `seed-series-${providerCode}-${isoDate}`,
      validationNotes:
        precip === null
          ? ['Observação em falta na série de demonstração (nunca convertida para 0 mm).']
          : ['Série de demonstração pré-carregada para validação de cenários.'],
    })
  }
  return results
}

